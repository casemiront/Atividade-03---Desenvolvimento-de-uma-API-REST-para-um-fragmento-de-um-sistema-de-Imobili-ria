CREATE TABLE perfis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(40) NOT NULL UNIQUE,
    descricao VARCHAR(200) NOT NULL
);
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL,
    id_cliente BIGINT,
    CONSTRAINT fk_usuario_cliente FOREIGN KEY(id_cliente) REFERENCES clientes(id)
);
CREATE TABLE usuario_perfis (
    id_usuario BIGINT NOT NULL,
    id_perfil BIGINT NOT NULL,
    PRIMARY KEY(id_usuario,id_perfil),
    CONSTRAINT fk_up_usuario FOREIGN KEY(id_usuario) REFERENCES usuarios(id),
    CONSTRAINT fk_up_perfil FOREIGN KEY(id_perfil) REFERENCES perfis(id)
);
CREATE INDEX idx_usuario_cliente ON usuarios(id_cliente);
